#!/usr/bin/env node
/**
 * Puts ZirZirCord online from this computer:
 *   Redis (Docker) + API server (this Mac) + Cloudflare quick tunnel (public HTTPS)
 *   + website rebuilt and deployed to Vercel pointing at the tunnel.
 * Database/files = Supabase, voice = LiveKit Cloud (from infra/.env.cloud).
 *
 *   npm run live              # everything
 *   npm run live -- --no-web  # don't redeploy the website (API only)
 *   npm run live -- --redeploy-web  # push website changes to the running live session
 *   npm run live -- --local-db      # use the local Docker Postgres (for networks that block port 5432)
 *
 * The site stays up while this keeps running (and the Mac stays awake). Ctrl+C stops it.
 */
import { execFileSync, spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { appendFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = path.join(root, 'infra/.env.cloud');
const stage = path.join(root, '.live/web');
const VERCEL_PROJECT = 'zirzircord';
const PORT = 4000;
const skipWeb = process.argv.includes('--no-web');
const localDb = process.argv.includes('--local-db');
const LOCAL_DB_URL = 'postgresql://zirzir:zirzir@localhost:5432/zirzircord';
const children = [];

const log = (...a) => console.log('\x1b[35m[live]\x1b[0m', ...a);
function killChildren() {
  for (const c of children) {
    try {
      c.kill('SIGTERM');
    } catch {}
  }
}
/** Print an error, stop the tunnel/server/keep-awake, and exit right away. */
const die = (msg) => {
  console.error('\x1b[31m[live]\x1b[0m', msg);
  killChildren();
  process.exit(1);
};

function shutdown(code = 0) {
  killChildren();
  setTimeout(() => process.exit(code), 500);
}
process.on('uncaughtException', (e) => die(e.stack ?? String(e)));
process.on('unhandledRejection', (e) => die(e?.stack ?? String(e)));
process.on('SIGINT', () => (log('stopping…'), shutdown(0)));
process.on('SIGTERM', () => shutdown(0));

function loadEnv() {
  if (!existsSync(envFile)) die('infra/.env.cloud not found (copy infra/.env.cloud.example and fill it in)');
  const env = {};
  for (const line of readFileSync(envFile, 'utf8').split('\n')) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) env[m[1]] = m[2];
  }
  for (const k of ['DATABASE_URL', 'S3_ENDPOINT', 'S3_REGION', 'S3_ACCESS_KEY', 'S3_SECRET_KEY', 'LIVEKIT_URL', 'LIVEKIT_API_KEY', 'LIVEKIT_API_SECRET']) {
    if (!env[k]) die(`${k} is empty in infra/.env.cloud`);
  }
  if (!env.JWT_SECRET) {
    env.JWT_SECRET = randomBytes(32).toString('hex');
    appendFileSync(envFile, `\n# Generated by scripts/live.mjs — keeps users signed in across restarts\nJWT_SECRET=${env.JWT_SECRET}\n`);
  }
  return env;
}

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { cwd: root, stdio: 'inherit', ...opts });
}

function startTunnel() {
  return new Promise((resolve, reject) => {
    const t = spawn('cloudflared', ['tunnel', '--no-autoupdate', '--url', `http://localhost:${PORT}`], { stdio: ['ignore', 'pipe', 'pipe'] });
    children.push(t);
    const timer = setTimeout(() => reject(new Error('cloudflared did not print a URL within 45s')), 45_000);
    const onData = (buf) => {
      const m = /https:\/\/[a-z0-9-]+\.trycloudflare\.com/.exec(buf.toString());
      if (m) {
        clearTimeout(timer);
        resolve(m[0]);
      }
    };
    t.stdout.on('data', onData);
    t.stderr.on('data', onData);
    t.on('exit', (code) => reject(new Error(`cloudflared exited (${code}). Is it installed? brew install cloudflared`)));
  });
}

/** True if a TCP connection to host:port succeeds within the timeout. */
function canReach(host, port, ms = 6000) {
  return new Promise((resolve) => {
    const sock = net.connect({ host, port });
    const done = (ok) => (sock.destroy(), resolve(ok));
    sock.setTimeout(ms, () => done(false));
    sock.once('connect', () => done(true));
    sock.once('error', () => done(false));
  });
}

async function waitForHealth(url, ms = 90_000) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try {
      const r = await fetch(`${url}/health`);
      if (r.ok) return true;
    } catch {}
    await new Promise((r) => setTimeout(r, 1500));
  }
  return false;
}

function vercel(args, opts = {}) {
  return execFileSync('npx', ['-y', 'vercel@latest', ...args], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts });
}

function deployWeb(apiUrl) {
  log('building website…');
  run('npm', ['run', 'build', '-w', '@zirzircord/web'], { env: { ...process.env, VITE_API_URL: apiUrl }, stdio: ['ignore', 'ignore', 'inherit'] });

  mkdirSync(stage, { recursive: true });
  for (const f of readdirSync(stage)) if (f !== '.vercel') rmSync(path.join(stage, f), { recursive: true, force: true });
  cpSync(path.join(root, 'apps/web/dist'), stage, { recursive: true });
  writeFileSync(
    path.join(stage, 'vercel.json'),
    JSON.stringify(
      {
        rewrites: [{ source: '/(.*)', destination: '/index.html' }],
        headers: [{ source: '/assets/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] }],
      },
      null,
      2,
    ),
  );

  if (!existsSync(path.join(stage, '.vercel/project.json'))) {
    log(`linking Vercel project "${VERCEL_PROJECT}"…`);
    try {
      vercel(['project', 'create', VERCEL_PROJECT]);
    } catch {
      /* already exists */
    }
    vercel(['link', '--yes', '--project', VERCEL_PROJECT, '--cwd', stage]);
  }
  log('deploying website to Vercel…');
  const out = vercel(['deploy', '--prod', '--yes', '--cwd', stage]);
  const urls = [...new Set(out.match(/https:\/\/[a-z0-9.-]+\.vercel\.app/g) ?? [])];
  return urls;
}

// ----------------------------------------------------------------------------

const apiUrlFile = path.join(root, '.live/api-url');

// `npm run live -- --redeploy-web`: push website changes without restarting the server/tunnel.
if (process.argv.includes('--redeploy-web')) {
  if (!existsSync(apiUrlFile)) die('No running live session found (.live/api-url missing). Start one with: npm run live');
  const url = readFileSync(apiUrlFile, 'utf8').trim();
  const urls = deployWeb(url);
  log(`website redeployed → ${urls.join(' , ')} (API ${url})`);
  process.exit(0);
}

const cfg = loadEnv();

const databaseUrl = localDb ? LOCAL_DB_URL : cfg.DATABASE_URL;
if (!localDb) {
  const { hostname, port } = new URL(cfg.DATABASE_URL);
  log(`checking Supabase database (${hostname}:${port || 5432})…`);
  if (!(await canReach(hostname, Number(port || 5432)))) {
    die(
      `Can't reach the Supabase database from this network: port ${port || 5432} is blocked here\n` +
        `  (common on school/office/public Wi-Fi). Either:\n` +
        `    • switch to another network (home Wi-Fi or phone hotspot), or\n` +
        `    • run:  npm run live -- --local-db   (uses a database on this Mac; files and voice still work)`,
    );
  }
}

log(`starting Redis${localDb ? ' + local Postgres' : ''} (Docker)…`);
try {
  run('docker', ['compose', 'up', '-d', 'redis', ...(localDb ? ['postgres'] : [])], { stdio: ['ignore', 'ignore', 'inherit'] });
} catch {
  die('Docker is not running. Start Docker Desktop and try again.');
}
if (localDb) {
  for (let i = 0; i < 30 && !(await canReach('localhost', 5432, 1000)); i++) await new Promise((r) => setTimeout(r, 1000));
}

log('building API server…');
try {
  run('npm', ['run', 'build', '-w', '@zirzircord/server'], { stdio: ['ignore', 'ignore', 'inherit'] });
} catch {
  die('Building the API server failed (see the error above).');
}

log('opening Cloudflare tunnel…');
let apiUrl;
try {
  apiUrl = await startTunnel();
} catch (e) {
  die(e.message);
}
log(`public API address: ${apiUrl}`);
mkdirSync(path.dirname(apiUrlFile), { recursive: true });
writeFileSync(apiUrlFile, apiUrl);

const serverEnv = {
  ...process.env,
  NODE_ENV: 'production',
  PORT: String(PORT),
  PUBLIC_API_URL: apiUrl,
  CORS_ORIGINS: `https://${VERCEL_PROJECT}*.vercel.app,http://localhost:5173`,
  DATABASE_URL: databaseUrl,
  REDIS_URL: 'redis://localhost:6379',
  JWT_SECRET: cfg.JWT_SECRET,
  PRESENCE_GRACE_SECONDS: '30',
  MAX_UPLOAD_MB: cfg.MAX_UPLOAD_MB ?? '100',
  S3_ENDPOINT: cfg.S3_ENDPOINT,
  S3_PUBLIC_ENDPOINT: cfg.S3_ENDPOINT,
  S3_REGION: cfg.S3_REGION,
  S3_BUCKET: cfg.S3_BUCKET ?? 'zirzircord',
  S3_ACCESS_KEY: cfg.S3_ACCESS_KEY,
  S3_SECRET_KEY: cfg.S3_SECRET_KEY,
  S3_FORCE_PATH_STYLE: 'true',
  LIVEKIT_URL: cfg.LIVEKIT_URL,
  LIVEKIT_API_KEY: cfg.LIVEKIT_API_KEY,
  LIVEKIT_API_SECRET: cfg.LIVEKIT_API_SECRET,
};

log('applying database migrations…');
try {
  run('npx', ['prisma', 'migrate', 'deploy'], { cwd: path.join(root, 'apps/server'), env: serverEnv, stdio: ['ignore', 'ignore', 'inherit'] });
} catch {
  die('Database migration failed (see the error above).');
}

log('starting API server…');
const server = spawn('node', ['dist/index.js'], { cwd: path.join(root, 'apps/server'), env: serverEnv, stdio: ['ignore', 'pipe', 'pipe'] });
children.push(server);
const serverLog = path.join(root, '.live/server.log');
mkdirSync(path.dirname(serverLog), { recursive: true });
writeFileSync(serverLog, '');
server.stdout.on('data', (d) => appendFileSync(serverLog, d));
server.stderr.on('data', (d) => (appendFileSync(serverLog, d), process.stderr.write(d)));
server.on('exit', (code) => die(`API server stopped (exit ${code}). See .live/server.log`));

// Keep the Mac awake while we're live.
if (process.platform === 'darwin') children.push(spawn('caffeinate', ['-i', '-w', String(process.pid)], { stdio: 'ignore' }));

if (!(await waitForHealth(apiUrl))) die(`API not reachable through the tunnel at ${apiUrl}. See .live/server.log`);
log('API is reachable through the tunnel ✔');

let siteUrls = [];
if (!skipWeb) {
  try {
    siteUrls = deployWeb(apiUrl);
  } catch (e) {
    console.error(e.stderr?.toString() ?? e.message);
    die('Vercel deploy failed (are you logged in? npx vercel@latest login)');
  }
}

console.log(`
\x1b[32m  ZirZirCord is live\x1b[0m
  Website : ${siteUrls.length ? siteUrls.join('\n            ') : '(not redeployed: --no-web)'}
  API     : ${apiUrl}
  Logs    : .live/server.log

  Mobile app: on the sign-in screen tap "Server" and enter the API address above.
  Keep this running (and the Mac awake). Ctrl+C to stop.
`);
