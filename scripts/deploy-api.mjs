#!/usr/bin/env node
/**
 * Deploys the API to an always-on VM (e.g. Oracle Cloud Always Free) over SSH:
 *   builds the Docker image here (linux/amd64), streams it to the VM, uploads infra/oracle/,
 *   writes the server's .env from infra/.env.cloud and (re)starts API + Redis + Caddy (HTTPS).
 *
 *   npm run deploy:api -- --host=ubuntu@1.2.3.4   # first time (the host is remembered)
 *   npm run deploy:api                            # later deploys
 *   npm run deploy:api -- --config-only           # only update .env / compose, no image rebuild
 *
 * Options: --key=~/.ssh/zirzircord_oracle  --platform=linux/amd64 (use linux/arm64 for Ampere A1)
 * The API address is https://<ip-with-dashes>.sslip.io unless API_DOMAIN is set in infra/.env.cloud.
 */
import { execFileSync, spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = path.join(root, 'infra/.env.cloud');
const hostFile = path.join(root, '.live/oracle-host');
const REMOTE_DIR = 'zirzircord';
const IMAGE = 'zirzircord-api:latest';

const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const flag = (name) => process.argv.includes(`--${name}`);
const log = (...a) => console.log('\x1b[36m[deploy-api]\x1b[0m', ...a);
const die = (msg) => {
  console.error('\x1b[31m[deploy-api]\x1b[0m', msg);
  process.exit(1);
};

// ---- target host ----
let host = arg('host');
if (host) {
  mkdirSync(path.dirname(hostFile), { recursive: true });
  writeFileSync(hostFile, host);
} else if (existsSync(hostFile)) {
  host = readFileSync(hostFile, 'utf8').trim();
} else {
  die('Pass the server once: npm run deploy:api -- --host=ubuntu@<public-ip>');
}
const key = (arg('key') ?? '~/.ssh/zirzircord_oracle').replace(/^~/, os.homedir());
if (!existsSync(key)) die(`SSH key not found: ${key}`);
const platform = arg('platform') ?? 'linux/amd64';
const sshArgs = ['-i', key, '-o', 'StrictHostKeyChecking=accept-new', '-o', 'ConnectTimeout=20', host];

/** Run a shell script on the server; `input` is piped to its stdin. */
function remote(script, { input, quiet } = {}) {
  return execFileSync('ssh', [...sshArgs, script], { input, stdio: [input === undefined ? 'ignore' : 'pipe', quiet ? 'pipe' : 'inherit', 'inherit'] });
}

// ---- settings ----
function loadEnv() {
  if (!existsSync(envFile)) die('infra/.env.cloud not found (copy infra/.env.cloud.example and fill it in)');
  const env = {};
  for (const line of readFileSync(envFile, 'utf8').split('\n')) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) env[m[1]] = m[2].trim();
  }
  for (const k of ['DATABASE_URL', 'S3_ENDPOINT', 'S3_REGION', 'S3_ACCESS_KEY', 'S3_SECRET_KEY', 'LIVEKIT_URL', 'LIVEKIT_API_KEY', 'LIVEKIT_API_SECRET']) {
    if (!env[k] || env[k].includes('<')) die(`${k} is empty or still a placeholder in infra/.env.cloud`);
  }
  if (!env.JWT_SECRET || env.JWT_SECRET.includes('<')) {
    env.JWT_SECRET = randomBytes(48).toString('hex');
    appendFileSync(envFile, `\n# Generated by scripts/deploy-api.mjs — keeps users signed in across deploys\nJWT_SECRET=${env.JWT_SECRET}\n`);
  }
  return env;
}

const cfg = loadEnv();
const ip = host.split('@').pop();
const domain = cfg.API_DOMAIN || `${ip.replace(/[.:]/g, '-')}.sslip.io`;
const apiUrl = `https://${domain}`;

const serverEnv = {
  API_DOMAIN: domain,
  PUBLIC_API_URL: apiUrl,
  // Exact origins only: a pattern like zirzircord*.vercel.app would also match anyone's
  // "zirzircord-xyz" Vercel project. localhost:14320 = the Tauri desktop app's UI.
  // Add preview deployments in infra/.env.cloud, e.g. https://zirzircord-*-<team>.vercel.app
  CORS_ORIGINS: cfg.CORS_ORIGINS || 'https://zirzircord.vercel.app,http://localhost:5173,http://localhost:14320',
  // 'log' lets older phone / Electron builds (without the app header) keep working during a rollout.
  CLIENT_CHECK: cfg.CLIENT_CHECK || 'enforce',
  SESSION_SLEEP_DAYS: cfg.SESSION_SLEEP_DAYS || '5',
  SESSION_DELETE_AFTER_SLEEP_DAYS: cfg.SESSION_DELETE_AFTER_SLEEP_DAYS || '30',
  DATABASE_URL: cfg.DATABASE_URL,
  JWT_SECRET: cfg.JWT_SECRET,
  PRESENCE_GRACE_SECONDS: cfg.PRESENCE_GRACE_SECONDS || '30',
  MAX_UPLOAD_MB: cfg.MAX_UPLOAD_MB || '100',
  S3_ENDPOINT: cfg.S3_ENDPOINT,
  S3_PUBLIC_ENDPOINT: cfg.S3_PUBLIC_ENDPOINT || cfg.S3_ENDPOINT,
  S3_REGION: cfg.S3_REGION,
  S3_BUCKET: cfg.S3_BUCKET || 'zirzircord',
  S3_ACCESS_KEY: cfg.S3_ACCESS_KEY,
  S3_SECRET_KEY: cfg.S3_SECRET_KEY,
  S3_FORCE_PATH_STYLE: 'true',
  LIVEKIT_URL: cfg.LIVEKIT_URL,
  LIVEKIT_API_KEY: cfg.LIVEKIT_API_KEY,
  LIVEKIT_API_SECRET: cfg.LIVEKIT_API_SECRET,
};
// Single quotes: Docker Compose then takes the value literally (no $-interpolation).
const dotenv = Object.entries(serverEnv)
  .map(([k, v]) => {
    if (v.includes("'")) die(`${k} contains a single quote, which the server .env can't hold`);
    return `${k}='${v}'`;
  })
  .join('\n');

// ---- deploy ----
log(`target ${host} → ${apiUrl}`);
remote(`mkdir -p ~/${REMOTE_DIR}`);

if (!flag('config-only')) {
  log(`building API image (${platform})…`);
  try {
    execFileSync('docker', ['buildx', 'build', '--platform', platform, '-f', 'apps/server/Dockerfile', '-t', IMAGE, '--load', '.'], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] });
  } catch {
    die('Docker build failed. Is Docker Desktop running?');
  }
  log('sending image to the server (a minute or two)…');
  await new Promise((resolve, reject) => {
    const save = spawn('docker', ['save', IMAGE], { stdio: ['ignore', 'pipe', 'inherit'] });
    const gzip = spawn('gzip', ['-1'], { stdio: ['pipe', 'pipe', 'inherit'] });
    const ssh = spawn('ssh', [...sshArgs, 'gunzip | sudo docker load'], { stdio: ['pipe', 'ignore', 'inherit'] });
    save.stdout.pipe(gzip.stdin);
    gzip.stdout.pipe(ssh.stdin);
    ssh.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`docker load failed (${code})`))));
  }).catch((e) => die(e.message));
}

log('uploading config…');
for (const f of ['docker-compose.yml', 'Caddyfile']) {
  remote(`cat > ~/${REMOTE_DIR}/${f}`, { input: readFileSync(path.join(root, 'infra/oracle', f)) });
}
remote(`umask 077 && cat > ~/${REMOTE_DIR}/.env`, { input: dotenv + '\n' });

log('starting API + Redis + Caddy…');
remote(`cd ~/${REMOTE_DIR} && sudo docker compose up -d --remove-orphans && sudo docker image prune -f >/dev/null`);

log('waiting for HTTPS health check (first run also fetches the certificate)…');
const end = Date.now() + 180_000;
let ok = false;
while (Date.now() < end && !ok) {
  try {
    ok = (await fetch(`${apiUrl}/health`)).ok;
  } catch {}
  if (!ok) await new Promise((r) => setTimeout(r, 3000));
}
if (!ok) {
  remote(`cd ~/${REMOTE_DIR} && sudo docker compose ps && sudo docker compose logs --tail=40 api caddy`);
  die(`API not reachable at ${apiUrl}/health (see the logs above)`);
}

console.log(`
\x1b[32m  API is live\x1b[0m: ${apiUrl}
  Website: npm run deploy:web -- --api-url=${apiUrl}
  Logs:    ssh -i ${key} ${host} 'cd ~/${REMOTE_DIR} && sudo docker compose logs -f api'
`);
